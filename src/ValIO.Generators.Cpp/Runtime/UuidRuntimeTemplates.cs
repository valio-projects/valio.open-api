using ValIO.Generators.Cpp.Models;

namespace ValIO.Generators.Cpp.Runtime;

/// <summary>Emits application UUID aliases independently of their checked JSON boundary adapters.</summary>
public static class UuidRuntimeTemplates
{
    /// <summary>The pure application UUID type-support header path.</summary>
    public const string TypesHeaderFileName = "Runtime/ValIOUuidTypes.h";

    /// <summary>The implementation-only UUID JSON adapter header path.</summary>
    public const string JsonHeaderFileName = "Runtime/ValIOUuidJson.h";

    /// <summary>Emits the selected provider's application alias without importing JSON or HTTP dependencies.</summary>
    /// <param name="backend">The explicitly selected UUID provider.</param>
    /// <returns>The UUID alias header.</returns>
    /// <exception cref="ArgumentOutOfRangeException">The backend is not a defined provider.</exception>
    public static string TypesHeader(CppUuidBackend backend)
    {
        var (include, typeName) = backend switch
        {
            CppUuidBackend.String => ("string", "std::string"),
            CppUuidBackend.BoostUuid => ("boost/uuid/uuid.hpp", "boost::uuids::uuid"),
            CppUuidBackend.StdUuid => ("uuid.h", "uuids::uuid"),
            CppUuidBackend.ModernUuid => ("modern-uuid/uuid.h", "muuid::uuid"),
            _ => throw new ArgumentOutOfRangeException(nameof(backend), backend, "Unknown C++ UUID provider."),
        };
        return $$"""
// Generated by ValIO — do not edit.
#pragma once
#include <{{include}}>

namespace ValIO {

/// @brief Application UUID representation selected explicitly by the generation configuration.
/// @details JSON parsing and serialization are provided separately by ValIOUuidJson.h.
using Uuid = {{typeName}};

} // namespace ValIO
""";
    }

    /// <summary>Emits strict, bidirectional UUID conversion using the selected provider's public APIs.</summary>
    /// <param name="backend">The non-string UUID provider selected for generated application models.</param>
    /// <returns>The implementation-only UUID JSON adapter.</returns>
    /// <exception cref="ArgumentException">The string backend was supplied because its generic string codec already performs validation.</exception>
    /// <exception cref="ArgumentOutOfRangeException">The backend is not a defined provider.</exception>
    public static string JsonHeader(CppUuidBackend backend)
    {
        var includes = backend switch
        {
            CppUuidBackend.BoostUuid => "#include <boost/uuid/string_generator.hpp>\n#include <boost/uuid/uuid_io.hpp>",
            CppUuidBackend.StdUuid or CppUuidBackend.ModernUuid => "",
            CppUuidBackend.String => throw new ArgumentException("The string UUID backend uses the existing checked string codec.", nameof(backend)),
            _ => throw new ArgumentOutOfRangeException(nameof(backend), backend, "Unknown C++ UUID provider."),
        };
        var read = backend switch
        {
            CppUuidBackend.BoostUuid => """
        try {
            return boost::uuids::string_generator{}(text);
        } catch (const std::runtime_error&) {
            Reject(source, "UUID provider rejected the canonical UUID value");
        }
""",
            CppUuidBackend.StdUuid => """
        const auto parsed = uuids::uuid::from_string(std::string_view(text));
        if (!parsed) Reject(source, "UUID provider rejected the canonical UUID value");
        return *parsed;
""",
            CppUuidBackend.ModernUuid => """
        const auto parsed = muuid::uuid::from_chars(text);
        if (!parsed) Reject(source, "UUID provider rejected the canonical UUID value");
        return *parsed;
""",
            _ => throw new ArgumentOutOfRangeException(nameof(backend), backend, "Unknown C++ UUID provider."),
        };
        var write = backend switch
        {
            CppUuidBackend.BoostUuid => "boost::uuids::to_string(value)",
            CppUuidBackend.StdUuid => "uuids::to_string(value)",
            CppUuidBackend.ModernUuid => "value.to_string()",
            _ => throw new ArgumentOutOfRangeException(nameof(backend), backend, "Unknown C++ UUID provider."),
        };
        return $$"""
// Generated by ValIO — do not edit.
#pragma once
#include <stdexcept>
#include <string>
#include <string_view>
{{includes}}
#include "ValIOUuidTypes.h"
#include "ValIOJsonValidation.h"

namespace ValIO::JsonDetail {

/// @brief Converts a selected UUID provider through strict canonical OpenAPI string values.
/// @details Accepts uppercase or lowercase hexadecimal digits, including nil and max UUIDs. Braces, compact forms,
/// misplaced hyphens, whitespace, embedded nulls, and trailing text are rejected before invoking permissive provider parsers.
template <>
struct Codec<ValIO::Uuid> {
    /// @brief Parses one canonical UUID string without imposing a UUID version or variant restriction.
    /// @param source JSON string containing exactly the canonical 8-4-4-4-12 representation.
    /// @param format Declared JSON wire format; UUID values always use UUID validation.
    /// @return The provider's value representation.
    /// @throws nlohmann::json::exception If the JSON value or UUID text is invalid.
    static ValIO::Uuid Read(const nlohmann::json& source, const JsonStringFormat format) {
        (void)format;
        if (!source.is_string()) Reject(source, "UUID value must be a JSON string");
        const auto& text = source.get_ref<const std::string&>();
        if (!IsUuid(text)) Reject(source, "UUID must use exactly the canonical 8-4-4-4-12 hexadecimal form");
{{read}}
    }

    /// @brief Serializes the complete UUID value as a lowercase canonical string, preserving nil and max values.
    /// @param value Application UUID value.
    /// @param format Declared JSON wire format; UUID values always use UUID validation.
    /// @return A JSON string containing exactly 36 canonical UUID characters.
    /// @throws nlohmann::json::exception If a provider returns a malformed representation.
    static nlohmann::json Write(const ValIO::Uuid& value, const JsonStringFormat format) {
        (void)format;
        const std::string text = {{write}};
        const nlohmann::json result = text;
        if (!IsUuid(text)) Reject(result, "UUID provider returned a noncanonical representation");
        return result;
    }
};

} // namespace ValIO::JsonDetail

namespace ValIO {

/// @brief Formats a provider UUID for path, query, header, or form parameters without changing its value.
/// @param value Application UUID value.
/// @param format Declared wire format; UUID values always retain canonical UUID formatting.
/// @return Lowercase canonical 8-4-4-4-12 UUID text.
/// @throws nlohmann::json::exception If the provider returns a malformed UUID representation.
inline std::string ToWireText(const Uuid& value, const JsonStringFormat format = JsonStringFormat::Uuid) {
    (void)format;
    return JsonDetail::Codec<Uuid>::Write(value, JsonStringFormat::Uuid).get<std::string>();
}

} // namespace ValIO
""";
    }

    /// <summary>Emits public model dependencies while accepting canonical upstream and Conan-provided targets.</summary>
    /// <param name="backend">The selected UUID representation.</param>
    /// <returns>CMake declarations following creation of the <c>valio_models</c> interface target.</returns>
    /// <exception cref="ArgumentOutOfRangeException">The backend is not a defined provider.</exception>
    public static string CmakeRequirements(CppUuidBackend backend) => backend switch
    {
        CppUuidBackend.String => string.Empty,
        CppUuidBackend.BoostUuid => """
if(NOT TARGET Boost::uuid AND NOT TARGET Boost::headers AND NOT TARGET Boost::boost AND NOT TARGET boost::boost)
    find_package(Boost REQUIRED)
endif()
if(TARGET Boost::uuid)
    target_link_libraries(valio_models INTERFACE Boost::uuid)
elseif(TARGET Boost::headers)
    target_link_libraries(valio_models INTERFACE Boost::headers)
elseif(TARGET Boost::boost)
    target_link_libraries(valio_models INTERFACE Boost::boost)
elseif(TARGET boost::boost)
    target_link_libraries(valio_models INTERFACE boost::boost)
else()
    message(FATAL_ERROR "Boost.Uuid requires an imported Boost headers target")
endif()
""",
        CppUuidBackend.StdUuid => """
if(NOT TARGET stduuid AND NOT TARGET stduuid::stduuid)
    find_package(stduuid REQUIRED CONFIG)
endif()
if(TARGET stduuid::stduuid)
    target_link_libraries(valio_models INTERFACE stduuid::stduuid)
else()
    target_link_libraries(valio_models INTERFACE stduuid)
endif()
""",
        CppUuidBackend.ModernUuid => """
if(NOT TARGET modern-uuid::modern-uuid AND NOT TARGET modern-uuid::modern-uuid-static AND NOT TARGET modern-uuid::modern-uuid-shared)
    find_package(modern-uuid REQUIRED CONFIG)
endif()
if(TARGET modern-uuid::modern-uuid)
    target_link_libraries(valio_models INTERFACE modern-uuid::modern-uuid)
elseif(TARGET modern-uuid::modern-uuid-static)
    target_link_libraries(valio_models INTERFACE modern-uuid::modern-uuid-static)
else()
    target_link_libraries(valio_models INTERFACE modern-uuid::modern-uuid-shared)
endif()
""",
        _ => throw new ArgumentOutOfRangeException(nameof(backend), backend, "Unknown C++ UUID provider."),
    };
}
