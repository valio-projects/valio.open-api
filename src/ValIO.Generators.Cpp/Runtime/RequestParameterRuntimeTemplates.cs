/// @brief Formats a present scalar collection element while rejecting ambiguous nested collections and explicit nulls.
/// @param value Scalar or nullable scalar leaf.
/// @param formatter Scalar wire codec.
/// @return Complete scalar text.
template <class T, class Formatter> std::string FormatLeaf(const T& value, Formatter& formatter) {
    using Value = std::decay_t<T>;
    static_assert(!IsVector<Value>::value, "Nested HTTP parameter collections require an explicit schema-aware codec");
    if constexpr (IsOptional<Value>::value) {
        if (!value) throw std::invalid_argument("An explicit null HTTP parameter has no supported textual representation");
        return FormatLeaf(*value, formatter);
    } else return std::string(formatter(value));
}

/// @brief Formats complete flat wire values before any request mutation, preserving presence separately from empty values.
/// @param value Typed scalar, optional, or flat vector.
/// @param formatter Scalar leaf codec.
/// @param nestedOptional Whether an outer optional already established presence.
/// @return No collection for absence, or owned independently formatted scalar leaves.
template <class T, class Formatter>
std::optional<std::vector<std::string>> CollectParameterValues(const T& value, Formatter& formatter, const bool nestedOptional = false) {
    using Value = std::decay_t<T>;
    if constexpr (IsOptional<Value>::value) {
        if (!value) {
            if (nestedOptional) throw std::invalid_argument("An explicit null HTTP parameter has no supported textual representation");
            return std::nullopt;
        }
        return CollectParameterValues(*value, formatter, true);
    } else if constexpr (IsVector<Value>::value) {
        using Element = typename UnwrapOptional<typename Value::value_type>::Type;
        static_assert(!IsVector<Element>::value, "Nested HTTP parameter collections require an explicit schema-aware codec");
        std::vector<std::string> encoded;
        encoded.reserve(value.size());
        for (const auto& element : value) encoded.push_back(FormatLeaf(element, formatter));
        return encoded;
    } else return std::vector<std::string>{FormatLeaf(value, formatter)};
}

/// @brief Joins header and form collection values while retaining omission and explicit scalar presence.
/// @param value Typed scalar, optional, or flat vector.
/// @param formatter Scalar leaf codec.
/// @param encoding Collection encoding.
/// @param append Receives complete unencoded textual values.
template <class T, class Formatter, class Append>
void AppendParameter(const T& value, Formatter& formatter, const CollectionEncoding encoding, Append& append) {
    if (encoding != CollectionEncoding::Repeated && encoding != CollectionEncoding::CommaSeparated
        && encoding != CollectionEncoding::SpaceSeparated && encoding != CollectionEncoding::PipeSeparated)
        throw std::invalid_argument("Unknown HTTP collection encoding");
    auto encoded = CollectParameterValues(value, formatter);
    if (!encoded) return;
    if (encoding == CollectionEncoding::Repeated) {
        for (auto& element : *encoded) append(std::move(element));
    } else {
        const char separator = encoding == CollectionEncoding::CommaSeparated ? ','
            : encoding == CollectionEncoding::SpaceSeparated ? ' ' : '|';
        std::string joined;
        bool first = true;
        for (const auto& element : *encoded) {
            if (!first) joined.push_back(separator);
            joined += element;
            first = false;
        }
        append(std::move(joined));
    }
}

