struct ParsedUrl {
    std::string Scheme;
    std::string Host;
    std::string Port;
    std::string BasePath;
};

ParsedUrl ParseBaseUrl(const std::string& url) {
    ParsedUrl parsed;
    std::string rest = url;
    const std::size_t schemeEnd = url.find("://");
    if (schemeEnd != std::string::npos) {
        parsed.Scheme = url.substr(0, schemeEnd);
        rest = url.substr(schemeEnd + 3);
    } else {
        parsed.Scheme = "http";
    }
    const std::size_t pathStart = rest.find('/');
    const std::string hostPort = pathStart == std::string::npos ? rest : rest.substr(0, pathStart);
    parsed.BasePath = pathStart == std::string::npos ? std::string() : rest.substr(pathStart);
    const std::size_t portStart = hostPort.find(':');
    if (portStart == std::string::npos) {
        parsed.Host = hostPort;
    } else {
        parsed.Host = hostPort.substr(0, portStart);
        parsed.Port = hostPort.substr(portStart + 1);
    }
    return parsed;
}

std::string AppendQuery(const std::string& path, const std::vector<std::pair<std::string, std::string>>& query) {
    if (query.empty()) {
        return path;
    }
    std::string target = path;
    target += target.find('?') == std::string::npos ? '?' : '&';
    for (std::size_t i = 0; i < query.size(); ++i) {
        if (i != 0) {
            target += '&';
        }
        target += UrlEncode(query[i].first);
        target += '=';
        target += UrlEncode(query[i].second);
    }
    return target;
}

bool IsTimeout(const httplib::Error error) {
    return error == httplib::Error::ConnectionTimeout;
}

bool HasRequestBody(const HttpVerb verb) {
    return verb == HttpVerb::Post || verb == HttpVerb::Put || verb == HttpVerb::Patch;
}

} // namespace

struct HttpClient::Impl {
    HttpConfig Config;
    std::string Scheme;
    std::string Host;
    std::string Port;
    std::string BasePath;
    std::unique_ptr<httplib::Client> Client;

    void EnsureClient() {
        if (Client) {
            return;
        }
        const int port = Port.empty() ? (Scheme == "https" ? 443 : 80) : std::stoi(Port);
        Client = std::make_unique<httplib::Client>(Scheme + "://" + Host + ":" + std::to_string(port));
        Client->set_connection_timeout(Config.ConnectTimeoutSeconds);
        Client->set_read_timeout(Config.ReadTimeoutSeconds);
        Client->set_keep_alive(Config.KeepAlive);
        if (!Config.ProxyHost.empty()) {
            Client->set_proxy(Config.ProxyHost, Config.ProxyPort);
        }
    }
};

void Request::SetFormBody(const std::vector<std::pair<std::string, std::string>>& fields) {
    FormFields = fields;
    Body.clear();
    FileParts.clear();
    ContentType = "application/x-www-form-urlencoded";
}

void Request::AddFilePart(std::string fieldName, std::string fileName, const std::vector<unsigned char>& bytes, std::string mimeType) {
    FilePart part;
    part.FieldName = std::move(fieldName);
    part.FileName = std::move(fileName);
    part.Bytes = bytes;
    part.MimeType = std::move(mimeType);
    FileParts.push_back(std::move(part));
}

namespace {

std::string EncodeFormFields(const std::vector<std::pair<std::string, std::string>>& fields) {
    std::string body;
    for (std::size_t i = 0; i < fields.size(); ++i) {
        if (i != 0) {
            body += '&';
        }
        body += UrlEncode(fields[i].first);
        body += '=';
        body += UrlEncode(fields[i].second);
    }
    return body;
}

std::string EscapePartName(const std::string& value) {
    std::string escaped;
    for (const char character : value) {
        if (character == '\r') {
            escaped += "%0D";
        } else if (character == '\n') {
            escaped += "%0A";
        } else {
            if (character == '\\' || character == '"') {
                escaped += '\\';
            }
            escaped += character;
        }
    }
    return escaped;
}

std::string EncodeMultipartBody(const Request& request, std::string& contentType) {
    std::string boundary = "----ValIOBoundary";
    for (;;) {
        bool collision = false;
        for (const auto& field : request.FormFields) {
            collision = collision || field.first.find(boundary) != std::string::npos
                || field.second.find(boundary) != std::string::npos;
        }
        for (const auto& part : request.FileParts) {
            const std::string bytes(part.Bytes.begin(), part.Bytes.end());
            collision = collision || bytes.find(boundary) != std::string::npos
                || part.FieldName.find(boundary) != std::string::npos
                || part.FileName.find(boundary) != std::string::npos;
        }
        if (!collision) {
            break;
        }
        boundary += '_';
    }

    contentType = "multipart/form-data; boundary=" + boundary;
    std::string body;
    for (const auto& field : request.FormFields) {
        body += "--" + boundary + "\r\nContent-Disposition: form-data; name=\""
            + EscapePartName(field.first) + "\"\r\n\r\n" + field.second + "\r\n";
    }
    for (const auto& part : request.FileParts) {
        body += "--" + boundary + "\r\nContent-Disposition: form-data; name=\""
            + EscapePartName(part.FieldName) + "\"; filename=\"" + EscapePartName(part.FileName)
            + "\"\r\nContent-Type: " + (part.MimeType.empty() ? "application/octet-stream" : part.MimeType)
            + "\r\n\r\n";
        body.append(part.Bytes.begin(), part.Bytes.end());
        body += "\r\n";
    }
    return body + "--" + boundary + "--\r\n";
}

} // namespace

std::string UrlEncode(const std::string& value) {
    static const char* const HexDigits = "0123456789ABCDEF";
    std::string encoded;
    encoded.reserve(value.size() * 3);
    for (const char c : value) {
        const unsigned char byte = static_cast<unsigned char>(c);
        const bool unreserved = (byte >= 'A' && byte <= 'Z')
            || (byte >= 'a' && byte <= 'z')
            || (byte >= '0' && byte <= '9')
            || byte == '-' || byte == '_' || byte == '.' || byte == '~';
        if (unreserved) {
            encoded += c;
        } else {
            encoded += '%';
            encoded += HexDigits[byte >> 4];
            encoded += HexDigits[byte & 0x0F];
        }
    }
    return encoded;
}

Error ErrorFromStatus(const int statusCode, const std::string& body) {
    Error error;
    error.What = Error::Code::Status;
    error.StatusCode = statusCode;
    error.Message = "HTTP status " + std::to_string(statusCode);
    error.Body = body;
    return error;
}

HttpClient::HttpClient(HttpConfig config) : _impl(new Impl()) {
    _impl->Config = std::move(config);
    const ParsedUrl parsed = ParseBaseUrl(_impl->Config.BaseUrl);
    _impl->Scheme = parsed.Scheme;
    _impl->Host = parsed.Host;
    _impl->Port = parsed.Port;
    _impl->BasePath = parsed.BasePath;
}

HttpClient::~HttpClient() { delete _impl; }

HttpClient::HttpClient(HttpClient&& other) noexcept : _impl(other._impl) { other._impl = nullptr; }

HttpClient& HttpClient::operator=(HttpClient&& other) noexcept {
    if (this != &other) {
        delete _impl;
        _impl = other._impl;
        other._impl = nullptr;
    }
    return *this;
}

Expected<Response, Error> HttpClient::Send(const Request& request) const {
#if !defined(CPPHTTPLIB_OPENSSL_SUPPORT)
    if (_impl->Scheme == "https") {
        Error error;
        error.What = Error::Code::Unsupported;
        error.Message = "HTTPS requires a cpp-httplib build with CPPHTTPLIB_OPENSSL_SUPPORT";
        return MakeError<Response>(error);
    }
#endif
    if (_impl->Host.empty()) {
        Error error;
        error.What = Error::Code::Transport;
        error.Message = "invalid base URL: " + _impl->Config.BaseUrl;
        return MakeError<Response>(error);
    }
    _impl->EnsureClient();

    std::string effectiveBody = request.Body;
    std::string effectiveContentType = request.ContentType;
    if (request.ContentType == "multipart/form-data" || !request.FileParts.empty()) {
        effectiveBody = EncodeMultipartBody(request, effectiveContentType);
    } else if (effectiveBody.empty() && !request.FormFields.empty()) {
        effectiveBody = EncodeFormFields(request.FormFields);
        effectiveContentType = "application/x-www-form-urlencoded";
    }

    const std::string target = AppendQuery(_impl->BasePath + request.Path, request.Query);
    httplib::Headers headers;
    for (const auto& header : request.Headers) {
        headers.insert(header);
    }
    if (HasRequestBody(request.Verb) && effectiveContentType == "application/json") {
        headers.insert(std::make_pair("Accept", "application/json"));
    }

    httplib::Result result = [&]() -> httplib::Result {
        switch (request.Verb) {
        case HttpVerb::Get:
            return _impl->Client->Get(target, headers);
        case HttpVerb::Head:
            return _impl->Client->Head(target, headers);
        case HttpVerb::Delete:
            return _impl->Client->Delete(target, headers);
        case HttpVerb::Post:
            return _impl->Client->Post(target, headers, effectiveBody, effectiveContentType);
        case HttpVerb::Put:
            return _impl->Client->Put(target, headers, effectiveBody, effectiveContentType);
        case HttpVerb::Patch:
            return _impl->Client->Patch(target, headers, effectiveBody, effectiveContentType);
        case HttpVerb::Options:
            return _impl->Client->Options(target, headers);
        }
        return httplib::Result(nullptr, httplib::Error::Success);
    }();

    if (!result) {
        const httplib::Error transportError = result.error();
        Error error;
        error.What = IsTimeout(transportError) ? Error::Code::Timeout : Error::Code::Transport;
        error.Message = httplib::to_string(transportError);
        return MakeError<Response>(error);
    }

    Response response;
    response.StatusCode = result->status;
    response.Body = result->body;
    return response;
}

