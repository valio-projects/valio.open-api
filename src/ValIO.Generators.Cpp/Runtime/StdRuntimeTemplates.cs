namespace ValIO.Generators.Cpp.Runtime;

/// <summary>
/// Emits the standard C++ runtime once per generated project, with third-party types confined to codec and HTTP implementations.
/// </summary>
public static class StdRuntimeTemplates
{
    /// <summary>The standalone result contract path.</summary>
    public const string ExpectedHeaderFileName = "Runtime/ValIOExpected.h";
    /// <summary>The structured error contract path.</summary>
    public const string ErrorHeaderFileName = "Runtime/ValIOError.h";
    /// <summary>The independent cancellation contract path.</summary>
    public const string CancellationHeaderFileName = "Runtime/ValIOCancellation.h";
    /// <summary>The HTTP contract path.</summary>
    public const string HttpHeaderFileName = "Runtime/ValIOHttp.h";
    /// <summary>The sole HTTP implementation translation unit path.</summary>
    public const string HttpSourceFileName = "Runtime/ValIOHttp.cpp";
    /// <summary>The checked client JSON helper path.</summary>
    public const string JsonHeaderFileName = "Runtime/ValIOJson.h";
    /// <summary>The JSON type-adapter header used by serializers without pulling in HTTP runtime code.</summary>
    public const string JsonTypesHeaderFileName = "Runtime/ValIOJsonTypes.h";
    /// <summary>The generated CMake project path.</summary>
    public const string CmakeListsFileName = "CMakeLists.txt";

    /// <summary>
    /// Emits separate model, serializer, and client targets with explicit dependency boundaries.
    /// </summary>
    /// <param name="cxxStandard">The target C++ language standard.</param>
    /// <param name="rootNamespace">The generated namespace used to name the CMake project.</param>
    /// <param name="temporalBackend">The explicit application temporal dependency.</param>
    /// <param name="uuidBackend">The explicit application UUID dependency.</param>
    /// <returns>The generated project definition.</returns>
    public static string CmakeLists(int cxxStandard, string rootNamespace,
        CppTemporalBackend temporalBackend = CppTemporalBackend.String, CppUuidBackend uuidBackend = CppUuidBackend.String)
    {
        var projectName = "ValIO_" + new string(rootNamespace.Where(char.IsLetterOrDigit).ToArray());
        return $$"""
# Generated by ValIO — do not edit.
# Link valio_models for pure DTO definitions, valio_serializers for JSON, or valio_clients for HTTP.
cmake_minimum_required(VERSION 3.16)
project({{projectName}} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD {{cxxStandard}})
set(CMAKE_CXX_STANDARD_REQUIRED ON)

add_library(valio_models INTERFACE)
target_include_directories(valio_models INTERFACE ${CMAKE_CURRENT_SOURCE_DIR})
target_compile_features(valio_models INTERFACE cxx_std_{{cxxStandard}})
{{TemporalRuntimeTemplates.CmakeRequirements(temporalBackend)}}
{{UuidRuntimeTemplates.CmakeRequirements(uuidBackend)}}

option(VALIO_BUILD_SERIALIZERS "Build JSON serializer implementations" ON)
option(VALIO_BUILD_CLIENTS "Build HTTP client implementations" ON)

file(GLOB_RECURSE VALIO_SERIALIZER_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/Serializers/*.cpp")
file(GLOB_RECURSE VALIO_CLIENT_SOURCES CONFIGURE_DEPENDS "${CMAKE_CURRENT_SOURCE_DIR}/Clients/*.cpp")
add_library(valio_generated INTERFACE)
target_link_libraries(valio_generated INTERFACE valio_models)

if(VALIO_BUILD_SERIALIZERS AND (VALIO_SERIALIZER_SOURCES OR VALIO_CLIENT_SOURCES))
    if(NOT TARGET nlohmann_json::nlohmann_json)
        find_package(nlohmann_json REQUIRED)
    endif()
    if(VALIO_SERIALIZER_SOURCES)
        add_library(valio_serializers STATIC ${VALIO_SERIALIZER_SOURCES})
        target_link_libraries(valio_serializers PUBLIC valio_models nlohmann_json::nlohmann_json)
    else()
        add_library(valio_serializers INTERFACE)
        target_link_libraries(valio_serializers INTERFACE valio_models nlohmann_json::nlohmann_json)
    endif()
    target_link_libraries(valio_generated INTERFACE valio_serializers)
endif()

if(VALIO_BUILD_CLIENTS AND VALIO_CLIENT_SOURCES)
    if(NOT TARGET valio_serializers)
        message(FATAL_ERROR "HTTP clients require VALIO_BUILD_SERIALIZERS=ON")
    endif()
    if(NOT TARGET httplib::httplib)
        find_package(httplib REQUIRED)
    endif()
    add_library(valio_clients STATIC ${VALIO_CLIENT_SOURCES} "${CMAKE_CURRENT_SOURCE_DIR}/Runtime/ValIOHttp.cpp")
    target_link_libraries(valio_clients PUBLIC valio_models valio_serializers PRIVATE httplib::httplib)
    target_link_libraries(valio_generated INTERFACE valio_clients)
endif()
""";
    }

    /// <summary>Emits the standard expected adapter and its C++17 fallback.</summary>
    /// <returns>The standalone result header.</returns>
    public static string ExpectedHeader() => """
// Generated by ValIO — do not edit.
// ValIO::Expected = std::expected при наличии (C++23+), иначе минималистичный polyfill.
// Один и тот же API в обоих режимах: has_value / operator bool / operator* / value / error / MakeError.
#pragma once
#include <utility>
#include <version>

#if defined(__cpp_lib_expected)

#include <expected>

namespace ValIO {

template <class T, class E>
using Expected = std::expected<T, E>;

template <class T, class E>
Expected<T, E> MakeError(E error) { return std::expected<T, E>(std::unexpected(std::move(error))); }

} // namespace ValIO

#else

namespace ValIO {

template <class E>
class Unexpected {
public:
    explicit Unexpected(E error) : _error(std::move(error)) {}
    const E& error() const noexcept { return _error; }
    E& error() noexcept { return _error; }
private:
    E _error;
};

template <class T, class E>
class Expected {
public:
    Expected() : _hasValue(true), _value(), _error() {}
    Expected(const T& value) : _hasValue(true), _value(value), _error() {}
    Expected(T&& value) : _hasValue(true), _value(std::move(value)), _error() {}
    Expected(Unexpected<E> unexpected) : _hasValue(false), _value(), _error(std::move(unexpected.error())) {}

    bool has_value() const noexcept { return _hasValue; }
    explicit operator bool() const noexcept { return _hasValue; }

    const T& operator*() const& noexcept { return _value; }
    T& operator*() & noexcept { return _value; }
    const T* operator->() const noexcept { return &_value; }
    T* operator->() noexcept { return &_value; }
    const T& value() const& noexcept { return _value; }
    T& value() & noexcept { return _value; }
    T&& value() && noexcept { return std::move(_value); }

    const E& error() const& noexcept { return _error; }
    E& error() & noexcept { return _error; }

private:
    bool _hasValue;
    T _value;
    E _error;
};

template <class E>
class Expected<void, E> {
public:
    Expected() : _hasValue(true), _error() {}
    Expected(Unexpected<E> unexpected) : _hasValue(false), _error(std::move(unexpected.error())) {}

    bool has_value() const noexcept { return _hasValue; }
    explicit operator bool() const noexcept { return _hasValue; }

    const E& error() const& noexcept { return _error; }
    E& error() & noexcept { return _error; }

private:
    bool _hasValue;
    E _error;
};

template <class T, class E>
Expected<T, E> MakeError(E error) { return Expected<T, E>(Unexpected<E>(std::move(error))); }

} // namespace ValIO

#endif
""";

    /// <summary>Emits structured errors for transport, status, decoding, interception, and cancellation failures.</summary>
    /// <returns>The standalone error header.</returns>
    public static string ErrorHeader() => """
// Generated by ValIO — do not edit.
#pragma once
#include <string>

namespace ValIO {

/// @brief Owns a failure category and optional raw HTTP diagnostics.
struct Error {
    /// @brief Closed failure categories returned by generated clients.
    enum class Code {
        Transport,   ///< The HTTP connection or request encoding failed.
        Timeout,     ///< The connection timeout elapsed.
        Status,      ///< The server returned an unsuccessful HTTP status.
        Parse,       ///< The response violates the declared JSON type or format.
        Serialization, ///< A request value violates its declared JSON type, wire format, or enum mapping.
        Unsupported, ///< The configured transport does not support the requested feature.
        Cancelled,   ///< The caller requested cancellation before completion.
        Interceptor, ///< An application interception or retry callback failed.
    };

    Code What = Code::Transport; ///< Failure category.
    int StatusCode = 0; ///< Received HTTP status, or zero when no status applies.
    std::string Message; ///< Diagnostic message without automatically logging request headers.
    std::string Body; ///< Raw response body retained by status and parse failures.
};

} // namespace ValIO
""";

