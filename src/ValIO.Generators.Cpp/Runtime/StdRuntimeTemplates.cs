/// Разбирает тело ответа в T через ADL from_json; ошибки nlohmann → Error{Parse}.
template <class T>
Expected<T, Error> Parse(const std::string_view body) {
    try {
        const nlohmann::json parsed = nlohmann::json::parse(body);
        if constexpr (std::is_void_v<T>) {
            (void)parsed;
            return Expected<T, Error>();
        } else {
            return parsed.template get<T>();
        }
    } catch (const nlohmann::json::exception& exception) {
        Error error;
        error.What = Error::Code::Parse;
        error.Message = exception.what();
        error.Body = std::string(body);
        return MakeError<T>(error);
    }
}

