    /// <summary>Emits nullable JSON adapters without importing HTTP or client result types.</summary>
    /// <param name="jsonInclude">The configured nlohmann JSON header.</param>
    /// <param name="temporalBackend">The selected application temporal representation.</param>
    /// <param name="uuidBackend">The selected application UUID representation.</param>
    /// <returns>The standalone serializer type-support header.</returns>
    public static string JsonTypesHeader(string jsonInclude,
        CppTemporalBackend temporalBackend = CppTemporalBackend.String, CppUuidBackend uuidBackend = CppUuidBackend.String) => $$"""
// Generated by ValIO — do not edit.
#pragma once
#include <optional>
#include "ValIOJsonValidation.h"

NLOHMANN_JSON_NAMESPACE_BEGIN

/// @brief Nullable values retain JSON null, including inside arrays and dictionaries.
template <class T>
struct adl_serializer<std::optional<T>> {
    /// @brief Serializes an engaged value recursively, or emits JSON null.
    /// @param target JSON destination.
    /// @param value Nullable application value.
    static void to_json(json& target, const std::optional<T>& value) {
        if (value) {
            target = *value;
        } else {
            target = nullptr;
        }
    }

    /// @brief Validates a non-null value recursively before engaging the destination.
    /// @param source JSON source.
    /// @param value Nullable destination.
    static void from_json(const json& source, std::optional<T>& value) {
        if (source.is_null()) {
            value.reset();
        } else {
            value = ValIO::ReadJson<T>(source);
        }
    }
};

NLOHMANN_JSON_NAMESPACE_END
{{(temporalBackend != CppTemporalBackend.String ? "#include \"ValIOTemporalJson.h\"" : "")}}
{{(uuidBackend != CppUuidBackend.String ? "#include \"ValIOUuidJson.h\"" : "")}}
""";

    /// <summary>Emits generic JSON conversion helpers for generated clients.</summary>
    /// <param name="jsonInclude">The configured nlohmann JSON header.</param>
    /// <returns>The standalone JSON conversion header.</returns>
    public static string JsonHeader(string jsonInclude) => $$"""
// Generated by ValIO — do not edit.
#pragma once
#include <string>
#include <string_view>
#include <type_traits>

#include "{{jsonInclude}}"

#include "ValIOError.h"
#include "ValIOExpected.h"
#include "ValIOJsonTypes.h"
#include "ValIOJsonValidation.h"

namespace ValIO {

/// @brief Parses JSON through checked scalar, collection, enum, and nested model codecs.
/// @tparam T Declared application representation.
/// @param body Raw JSON response body.
/// @param format OpenAPI wire format used for strings or their collections.
/// @return A validated value, or a parse error retaining the raw response body.
template <class T>
Expected<T, Error> Parse(const std::string_view body, const JsonStringFormat format = JsonStringFormat::Plain) {
    try {
        const nlohmann::json parsed = nlohmann::json::parse(body);
        if constexpr (std::is_void_v<T>) {
            (void)parsed;
            return Expected<T, Error>();
        } else {
            return ReadJson<T>(parsed, format);
        }
    } catch (const nlohmann::json::exception& exception) {
        Error error;
        error.What = Error::Code::Parse;
        error.Message = exception.what();
        error.Body = std::string(body);
        return MakeError<T>(error);
    }
}

/// @brief Validates and serializes an application value through its declared JSON codec.
/// @tparam T Declared application representation.
/// @param value Application value to serialize.
/// @param format OpenAPI wire format used for strings or their collections.
/// @return Serialized JSON text.
/// @throws nlohmann::json::exception If the value violates the declared wire format.
template <class T>
std::string Dump(const T& value, const JsonStringFormat format = JsonStringFormat::Plain) {
    nlohmann::json serialized = WriteJson<T>(value, format);
    return serialized.dump();
}

} // namespace ValIO
""";
}
