using System.Globalization;
using System.Text;
using ValIO.Generators.Cpp.Models;

namespace ValIO.Generators.Cpp.Runtime;

/// <summary>Builds and prints the standalone SDK's targets and package dependencies.</summary>
internal static class CmakeProject
{
    /// <summary>Describes an argument printed in a CMake statement.</summary>
    /// <param name="Text">The argument's value, variable name or keyword.</param>
    /// <param name="Kind">The quoting and expansion convention.</param>
    /// <param name="Suffix">A path relative to a variable expansion, when supplied.</param>
    private sealed record Argument(string Text, ArgumentKind Kind = ArgumentKind.Token, string Suffix = "");

    /// <summary>The syntax for a CMake argument.</summary>
    private enum ArgumentKind
    {
        /// <summary>A standalone keyword, target or scalar.</summary>
        Token,
        /// <summary>A quoted string literal.</summary>
        Quoted,
        /// <summary>An unquoted variable expansion.</summary>
        Variable,
        /// <summary>A path rooted at a quoted variable expansion.</summary>
        RootedPath,
    }

    /// <summary>A statement within a CMake file or conditional branch.</summary>
    private abstract record Statement;

    /// <summary>A CMake function or built-in command call.</summary>
    /// <param name="Name">The command name.</param>
    /// <param name="Arguments">The ordered arguments.</param>
    private sealed record Command(string Name, IReadOnlyList<Argument> Arguments) : Statement;

    /// <summary>A condition with one matching body.</summary>
    /// <param name="Tokens">The individual tokens that form the condition.</param>
    /// <param name="Statements">The statements selected by the condition.</param>
    private sealed record Branch(IReadOnlyList<string> Tokens, IReadOnlyList<Statement> Statements);

    /// <summary>A sequence of conditional branches with an optional alternative.</summary>
    /// <param name="Branches">The conditions in evaluation order.</param>
    /// <param name="Otherwise">The alternative statements, if any.</param>
    private sealed record Conditional(IReadOnlyList<Branch> Branches, IReadOnlyList<Statement>? Otherwise = null) : Statement;

    /// <summary>Builds the file for the standalone C++ project profile.</summary>
    /// <param name="standard">The selected C++ language standard.</param>
    /// <param name="ns">The generated namespace used as project name data.</param>
    /// <param name="temporal">The selected temporal provider.</param>
    /// <param name="uuid">The selected UUID provider.</param>
    /// <returns>The printed CMake project.</returns>
    internal static string Render(int standard, string ns, CppTemporalBackend temporal, CppUuidBackend uuid)
    {
        var number = standard.ToString(CultureInfo.InvariantCulture);
        var project = "ValIO_" + new string(ns.Where(char.IsLetterOrDigit).ToArray());
        var statements = new List<Statement>
        {
            Cmd("cmake_minimum_required", "VERSION", "3.16"),
            Cmd("project", project, "LANGUAGES", "CXX"),
            Cmd("set", "CMAKE_CXX_STANDARD", number),
            Cmd("set", "CMAKE_CXX_STANDARD_REQUIRED", "ON"),
            Cmd("add_library", "valio_models", "INTERFACE"),
            new Command("target_include_directories", [new("valio_models"), new("INTERFACE"), new("CMAKE_CURRENT_SOURCE_DIR", ArgumentKind.Variable)]),
            Cmd("target_compile_features", "valio_models", "INTERFACE", "cxx_std_" + number),
        };
        statements.AddRange(TemporalDependencies(temporal));
        statements.AddRange(UuidDependencies(uuid));
        statements.AddRange([
            Option("VALIO_BUILD_SERIALIZERS", "Build JSON serializer implementations"),
            Option("VALIO_BUILD_CLIENTS", "Build HTTP client implementations"),
            Glob("VALIO_SERIALIZER_SOURCES", "/Serializers/*.cpp"),
            Glob("VALIO_CLIENT_SOURCES", "/Clients/*.cpp"),
            Cmd("add_library", "valio_generated", "INTERFACE"),
            Cmd("target_link_libraries", "valio_generated", "INTERFACE", "valio_models"),
            Serializers(),
            Clients(),
        ]);

        var output = new StringBuilder();
        output.AppendLine("# Generated by ValIO — do not edit.");
        output.AppendLine("# Link valio_models for DTOs, valio_serializers for JSON, or valio_clients for HTTP.");
        Print(output, statements, 0);
        return output.ToString();
    }

    /// <summary>Builds the conditional JSON target and its imported dependency.</summary>
    /// <returns>The target declaration block.</returns>
    private static Conditional Serializers() => If(
        ["VALIO_BUILD_SERIALIZERS", "AND", "(", "VALIO_SERIALIZER_SOURCES", "OR", "VALIO_CLIENT_SOURCES", ")"],
        RequirePackage("nlohmann_json", false, "nlohmann_json::nlohmann_json"),
        new Conditional(
            [new Branch(["VALIO_SERIALIZER_SOURCES"],
                [
                    new Command("add_library", [new("valio_serializers"), new("STATIC"), new("VALIO_SERIALIZER_SOURCES", ArgumentKind.Variable)]),
                    Cmd("target_link_libraries", "valio_serializers", "PUBLIC", "valio_models", "nlohmann_json::nlohmann_json"),
                ])],
            [
                Cmd("add_library", "valio_serializers", "INTERFACE"),
                Cmd("target_link_libraries", "valio_serializers", "INTERFACE", "valio_models", "nlohmann_json::nlohmann_json"),
            ]),
        Cmd("target_link_libraries", "valio_generated", "INTERFACE", "valio_serializers"));

    /// <summary>Builds the HTTP target with its standalone transport translation unit.</summary>
    /// <returns>The guarded HTTP target declarations.</returns>
    private static Conditional Clients() => If(["VALIO_BUILD_CLIENTS", "AND", "VALIO_CLIENT_SOURCES"],
        If(["NOT", "TARGET", "valio_serializers"], Error("HTTP clients require VALIO_BUILD_SERIALIZERS=ON")),
        RequirePackage("httplib", false, "httplib::httplib"),
        new Command("add_library", [new("valio_clients"), new("STATIC"), new("VALIO_CLIENT_SOURCES", ArgumentKind.Variable),
            new("CMAKE_CURRENT_SOURCE_DIR", ArgumentKind.RootedPath, "/Runtime/ValIOHttp.cpp")]),
        Cmd("target_link_libraries", "valio_clients", "PUBLIC", "valio_models", "valio_serializers", "PRIVATE", "httplib::httplib"),
        Cmd("target_link_libraries", "valio_generated", "INTERFACE", "valio_clients"));

    /// <summary>Builds package dependencies required by a native temporal provider.</summary>
    /// <param name="temporal">The selected provider.</param>
    /// <returns>Commands for the provider's public link dependencies.</returns>
    private static IEnumerable<Statement> TemporalDependencies(CppTemporalBackend temporal) => temporal switch
    {
        CppTemporalBackend.String or CppTemporalBackend.Chrono or CppTemporalBackend.Valio => [],
        CppTemporalBackend.HowardDate => [RequirePackage("date", true, "date::date"), LinkModel("date::date")],
        CppTemporalBackend.BoostDateTime => Provider("Boost", false, ["Boost::headers", "Boost::boost", "boost::boost"],
            Error("Boost.Date_Time requires an imported Boost headers target")),
        _ => throw new ArgumentOutOfRangeException(nameof(temporal), temporal, "Unknown C++ temporal provider."),
    };

    /// <summary>Builds package dependencies required by a native UUID provider.</summary>
    /// <param name="uuid">The selected provider.</param>
    /// <returns>Commands for the provider's public link dependencies.</returns>
    private static IEnumerable<Statement> UuidDependencies(CppUuidBackend uuid) => uuid switch
    {
        CppUuidBackend.String => [],
        CppUuidBackend.BoostUuid => Provider("Boost", false, ["Boost::uuid", "Boost::headers", "Boost::boost", "boost::boost"],
            Error("Boost.Uuid requires an imported Boost headers target")),
        CppUuidBackend.StdUuid => Provider("stduuid", true, ["stduuid::stduuid", "stduuid"], LinkModel("stduuid")),
        CppUuidBackend.ModernUuid => Provider("modern-uuid", true,
            ["modern-uuid::modern-uuid", "modern-uuid::modern-uuid-static", "modern-uuid::modern-uuid-shared"],
            LinkModel("modern-uuid::modern-uuid-shared")),
        _ => throw new ArgumentOutOfRangeException(nameof(uuid), uuid, "Unknown C++ UUID provider."),
    };

    /// <summary>Finds a package when needed and links one of its exported targets in priority order.</summary>
    /// <param name="package">The dependency package.</param>
    /// <param name="config">Whether to use CMake's config package mode.</param>
    /// <param name="targets">Accepted target names in priority order.</param>
    /// <param name="fallback">The final link or diagnostic when no branch selects a target.</param>
    /// <returns>The package and target selection statements.</returns>
    private static Statement[] Provider(string package, bool config, IReadOnlyList<string> targets, Command fallback)
    {
        var testedTargets = fallback.Name == "message" ? targets : targets.Take(targets.Count - 1);
        var branches = testedTargets.Select(target => new Branch(["TARGET", target], [LinkModel(target)])).ToArray();
        return [RequirePackage(package, config, targets.ToArray()), new Conditional(branches, [fallback])];
    }

    /// <summary>Finds a CMake package only when none of the accepted targets is present.</summary>
    /// <param name="package">The package to locate.</param>
    /// <param name="config">Whether to require the upstream config file.</param>
    /// <param name="targets">The existing targets that can satisfy the dependency.</param>
    /// <returns>The conditional package lookup.</returns>
    private static Conditional RequirePackage(string package, bool config, params string[] targets)
    {
        var condition = new List<string>();
        foreach (var target in targets)
        {
            if (condition.Count > 0)
                condition.Add("AND");
            condition.AddRange(["NOT", "TARGET", target]);
        }
        return If(condition, config ? Cmd("find_package", package, "REQUIRED", "CONFIG") : Cmd("find_package", package, "REQUIRED"));
    }

    /// <summary>Links a public dependency to the model interface target.</summary>
    /// <param name="target">The selected imported dependency.</param>
    /// <returns>The link command.</returns>
    private static Command LinkModel(string target) => Cmd("target_link_libraries", "valio_models", "INTERFACE", target);

    /// <summary>Creates a CMake command from unquoted individual tokens.</summary>
    /// <param name="name">The command name.</param>
    /// <param name="tokens">Its arguments.</param>
    /// <returns>The command node.</returns>
    private static Command Cmd(string name, params string[] tokens) => new(name, tokens.Select(token => new Argument(token)).ToArray());

    /// <summary>Creates a command with a fatal diagnostic.</summary>
    /// <param name="message">The diagnostic text.</param>
    /// <returns>The CMake message command.</returns>
    private static Command Error(string message) => new("message", [new("FATAL_ERROR"), new(message, ArgumentKind.Quoted)]);

    /// <summary>Declares a default-on build option.</summary>
    /// <param name="name">The option identifier.</param>
    /// <param name="description">The description shown by CMake.</param>
    /// <returns>The option command.</returns>
    private static Command Option(string name, string description) => new("option", [new(name), new(description, ArgumentKind.Quoted), new("ON")]);

    /// <summary>Collects generated sources under the current project directory.</summary>
    /// <param name="result">The CMake variable to fill.</param>
    /// <param name="pattern">The relative source file glob.</param>
    /// <returns>The file command.</returns>
    private static Command Glob(string result, string pattern) => new("file",
        [new("GLOB_RECURSE"), new(result), new("CONFIGURE_DEPENDS"), new("CMAKE_CURRENT_SOURCE_DIR", ArgumentKind.RootedPath, pattern)]);

    /// <summary>Builds a single conditional branch.</summary>
    /// <param name="condition">The condition's token sequence.</param>
    /// <param name="statements">The branch body.</param>
    /// <returns>A conditional block.</returns>
    private static Conditional If(IReadOnlyList<string> condition, params Statement[] statements) => new([new Branch(condition, statements)]);

    /// <summary>Prints commands and nested branches in their declared order.</summary>
    /// <param name="output">The output buffer.</param>
    /// <param name="statements">The current block to print.</param>
    /// <param name="level">The current indentation level.</param>
    private static void Print(StringBuilder output, IEnumerable<Statement> statements, int level)
    {
        var indent = new string(' ', level * 4);
        foreach (var statement in statements)
        {
            if (statement is Command command)
            {
                Line(command.Name, command.Arguments.Select(PrintArgument));
                continue;
            }

            var conditional = (Conditional)statement;
            var keyword = "if";
            foreach (var branch in conditional.Branches)
            {
                Line(keyword, branch.Tokens);
                Print(output, branch.Statements, level + 1);
                keyword = "elseif";
            }

            if (conditional.Otherwise is { } alternative)
            {
                Line("else", []);
                Print(output, alternative, level + 1);
            }
            Line("endif", []);
        }

        void Line(string name, IEnumerable<string> parts) =>
            output.Append(indent).Append(name).Append('(').AppendJoin(' ', parts).AppendLine(")");
    }

    /// <summary>Formats a CMake argument with its specified quoting and expansion.</summary>
    /// <param name="argument">The argument to print.</param>
    /// <returns>The rendered argument token.</returns>
    private static string PrintArgument(Argument argument) => argument.Kind switch
    {
        ArgumentKind.Quoted => $"\"{argument.Text}\"",
        ArgumentKind.Variable => "${" + argument.Text + "}",
        ArgumentKind.RootedPath => "\"${" + argument.Text + "}" + argument.Suffix + "\"",
        _ => argument.Text,
    };
}
