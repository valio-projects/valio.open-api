/** @brief Resolves one RFC 4648 base64 digit, rejecting whitespace and alternate alphabets. */
inline int Base64Digit(const char value) {
    if (value >= 'A' && value <= 'Z') return value - 'A';
    if (value >= 'a' && value <= 'z') return value - 'a' + 26;
    if (value >= '0' && value <= '9') return value - '0' + 52;
    if (value == '+') return 62;
    if (value == '/') return 63;
    return -1;
}

/** @brief Decodes canonical padded base64 without losing zero bytes or accepting malformed padding. */
inline std::vector<std::uint8_t> DecodeBase64(const nlohmann::json& source, const std::string_view text) {
    if (text.size() % 4 != 0) Reject(source, "invalid base64 length");
    std::vector<std::uint8_t> result;
    result.reserve(text.size() / 4 * 3);
    for (std::size_t offset = 0; offset < text.size(); offset += 4) {
        const int a = Base64Digit(text[offset]);
        const int b = Base64Digit(text[offset + 1]);
        const bool padC = text[offset + 2] == '=';
        const bool padD = text[offset + 3] == '=';
        const int c = padC ? 0 : Base64Digit(text[offset + 2]);
        const int d = padD ? 0 : Base64Digit(text[offset + 3]);
        if (a < 0 || b < 0 || c < 0 || d < 0 || (padC && !padD)
            || ((padC || padD) && offset + 4 != text.size())
            || (padC && (b & 15) != 0) || (padD && !padC && (c & 3) != 0)) Reject(source, "invalid base64 alphabet or padding");
        result.push_back(static_cast<std::uint8_t>((a << 2) | (b >> 4)));
        if (!padC) result.push_back(static_cast<std::uint8_t>((b << 4) | (c >> 2)));
        if (!padD) result.push_back(static_cast<std::uint8_t>((c << 6) | d));
    }
    return result;
}

/** @brief Encodes bytes as canonical RFC 4648 base64 text, including embedded zero bytes. */
inline std::string EncodeBase64(const std::vector<std::uint8_t>& bytes) {
    static constexpr std::string_view Alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::string result;
    for (std::size_t offset = 0; offset < bytes.size(); offset += 3) {
        const auto a = bytes[offset];
        const unsigned int b = offset + 1 < bytes.size() ? bytes[offset + 1] : 0;
        const unsigned int c = offset + 2 < bytes.size() ? bytes[offset + 2] : 0;
        result += Alphabet[a >> 2];
        result += Alphabet[((a & 3) << 4) | (b >> 4)];
        result += offset + 1 < bytes.size() ? Alphabet[((b & 15) << 2) | (c >> 6)] : '=';
        result += offset + 2 < bytes.size() ? Alphabet[c & 63] : '=';
    }
    return result;
}

/** @brief Provides scalar/model decoding and validates before any integral narrowing. */
template<class T, class = void>
struct Codec {
    /** @brief Reads a scalar or delegates a model/enum to its checked ADL codec. */
    static T Read(const nlohmann::json& source, const JsonStringFormat format) {
        (void)format;
        if constexpr (std::is_same_v<T, bool>) {
            if (!source.is_boolean()) Reject(source, "expected JSON boolean");
            return source.template get<T>();
        } else if constexpr (std::is_same_v<T, std::nullptr_t>) {
            if (!source.is_null()) Reject(source, "expected JSON null");
            return nullptr;
        } else if constexpr (std::is_integral_v<T>) {
            if (source.is_number_unsigned()) {
                const auto number = source.template get<std::uint64_t>();
                if (number > static_cast<std::uint64_t>((std::numeric_limits<T>::max)())) Reject(source, "JSON integer exceeds target range");
                return static_cast<T>(number);
            }
            if (source.is_number_integer()) {
                const auto number = source.template get<std::int64_t>();
                if constexpr (std::is_signed_v<T>) {
                    if (number < static_cast<std::int64_t>((std::numeric_limits<T>::lowest)())
                        || number > static_cast<std::int64_t>((std::numeric_limits<T>::max)())) Reject(source, "JSON integer exceeds target range");
                } else {
                    if (number < 0 || static_cast<std::uint64_t>(number) > static_cast<std::uint64_t>((std::numeric_limits<T>::max)())) Reject(source, "JSON integer exceeds target range");
                }
                return static_cast<T>(number);
            }
            if (!source.is_number_float()) Reject(source, "expected JSON integer");
            const double number = source.template get<double>();
            const double upper = std::ldexp(1.0, std::numeric_limits<T>::digits);
            const double lower = std::is_signed_v<T> ? -upper : 0.0;
            if (!std::isfinite(number) || std::trunc(number) != number || number < lower || number >= upper) Reject(source, "JSON number is fractional or exceeds integer range");
            return static_cast<T>(number);
        } else if constexpr (std::is_floating_point_v<T>) {
            if (!source.is_number()) Reject(source, "expected JSON number");
            const double number = source.template get<double>();
            if (!std::isfinite(number) || number < -(std::numeric_limits<T>::max)() || number > (std::numeric_limits<T>::max)()) Reject(source, "JSON number exceeds finite target range");
            return source.template get<T>();
        } else if constexpr (std::is_same_v<T, std::string>) {
            if (!source.is_string()) Reject(source, "expected JSON string");
            CheckString(source, source.template get_ref<const std::string&>(), format);
            return source.template get<T>();
        } else {
            return source.template get<T>();
        }
    }

    /** @brief Writes a scalar or model while enforcing finite numbers and declared string formats. */
    static nlohmann::json Write(const T& value, const JsonStringFormat format) {
        (void)format;
        nlohmann::json result = value;
        if constexpr (std::is_floating_point_v<T>) {
            if (!std::isfinite(value)) Reject(result, "cannot serialize a non-finite JSON number");
        } else if constexpr (std::is_same_v<T, std::string>) {
            CheckString(result, value, format);
        }
        return result;
    }
};

