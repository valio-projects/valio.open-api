    const int offsetMinute = Digits(text, offset + 4, 2);
    return offsetHour >= 0 && offsetHour <= 23 && offsetMinute >= 0 && offsetMinute <= 59;
}

/** @brief Checks canonical UUID syntax without narrowing allowed UUID versions or excluding the nil UUID. */
inline bool IsUuid(const std::string_view text) {
