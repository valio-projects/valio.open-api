/** @brief Checks every collection element rather than relying on unchecked container get conversions. */
template<class T, class Allocator>
struct Codec<std::vector<T, Allocator>> {
    /** @brief Reads an array, or an OpenAPI base64/binary string for byte collections. */
    static std::vector<T, Allocator> Read(const nlohmann::json& source, const JsonStringFormat format) {
        if constexpr (std::is_same_v<T, std::uint8_t>) {
            if (format == JsonStringFormat::Base64 || format == JsonStringFormat::Binary) {
                if (!source.is_string()) Reject(source, "expected OpenAPI binary JSON string");
                const auto& text = source.template get_ref<const std::string&>();
                if (format == JsonStringFormat::Base64) {
                    const auto decoded = DecodeBase64(source, text);
                    return std::vector<T, Allocator>(decoded.begin(), decoded.end());
                }
                return std::vector<T, Allocator>(text.begin(), text.end());
            }
        }
        if (!source.is_array()) Reject(source, "expected JSON array");
        std::vector<T, Allocator> result;
        result.reserve(source.size());
        for (const auto& item : source) result.push_back(Codec<T>::Read(item, format));
        return result;
    }
    /** @brief Writes every checked element, preserving base64 string wire representation for bytes. */
    static nlohmann::json Write(const std::vector<T, Allocator>& values, const JsonStringFormat format) {
        if constexpr (std::is_same_v<T, std::uint8_t>) {
            if (format == JsonStringFormat::Base64) return EncodeBase64(std::vector<std::uint8_t>(values.begin(), values.end()));
            if (format == JsonStringFormat::Binary) return std::string(values.begin(), values.end());
        }
        auto result = nlohmann::json::array();
        for (const auto& item : values) result.push_back(Codec<T>::Write(item, format));
        return result;
    }
};

/** @brief Validates string-keyed dictionary values recursively, including nullable values and nested models. */
