}

/** @brief Checks the Gregorian calendar, including leap years and exact date separators. */
inline bool IsDate(const std::string_view text) {
    if (text.size() != 10 || text[4] != '-' || text[7] != '-') return false;
    const int year = Digits(text, 0, 4);
    const int month = Digits(text, 5, 2);
    const int day = Digits(text, 8, 2);
    if (year < 0 || month < 1 || month > 12 || day < 1) return false;
    static constexpr std::array<int, 12> MonthDays { 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31 };
    const bool leap = year % 4 == 0 && (year % 100 != 0 || year % 400 == 0);
    return day <= MonthDays[static_cast<std::size_t>(month - 1)] + ((month == 2 && leap) ? 1 : 0);
}

/** @brief Checks RFC 3339 full-time syntax with a mandatory UTC offset and optional fractional seconds.
 * @details The RFC's leap-second value 60 is accepted; historical leap-second tables are not consulted.
 */
inline bool IsTime(const std::string_view text) {
