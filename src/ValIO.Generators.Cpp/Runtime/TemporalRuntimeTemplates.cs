}

/** @brief Converts decimal fractions to exact nanoseconds, rejecting discarded nonzero digits. */
inline std::uint64_t Nanoseconds(const std::string_view fraction) {
    std::uint64_t value = 0;
    for (std::size_t index = 0; index < 9; ++index) {
        value = value * 10 + (index < fraction.size() ? static_cast<unsigned int>(fraction[index] - '0') : 0);
    }
    for (std::size_t index = 9; index < fraction.size(); ++index) if (fraction[index] != '0') Fail("temporal fractional precision exceeds native nanoseconds");
    return value;
}

