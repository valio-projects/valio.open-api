using ValIO.Core.Ast.Enums;
using ValIO.Core.Ast.Nodes;
using ValIO.Core.Ast.Nodes.Expressions;
using ValIO.Core.Ast.Nodes.Statements;
using ValIO.Core.Ast.Nodes.Types;
using ValIO.Core.Interfaces;
using ValIO.Core.IR;
using ValIO.Core.IR.Builders;
using ValIO.Core.Plugins;
using ValIO.Generators.TypeScript.Ast.Nodes;
using ValIO.Generators.TypeScript.Ast.Nodes.Expressions;
using ValIO.Generators.TypeScript.Options;

namespace ValIO.Generators.TypeScript.Ast.Builders;

/// <summary>Lowers SignalR calls to a typed TypeScript module around the official connection.</summary>
/// <param name="naming">The converter that names the generated files and constants.</param>
internal sealed class TypeScriptSignalRAstBuilder(INamingConverter naming)
{
    /// <summary>Builds one hub module containing its path and a connection factory.</summary>
    /// <param name="context">The profile with its model layout and type mapping.</param>
    /// <param name="hub">The validated hub contract.</param>
    /// <returns>The source file tree and its explicit imports.</returns>
    /// <exception cref="InvalidOperationException">A wire type cannot be read exactly by the JavaScript runtime.</exception>
    internal SourceFileNode Build(GenerationContext context, IrSignalRHub hub)
    {
        var types = hub.Methods.Concat(hub.Events).SelectMany(call =>
            call.Result is null ? call.Parameters.Select(parameter => parameter.Type) :
                call.Parameters.Select(parameter => parameter.Type).Append(call.Result)).ToArray();
        if (types.Any(type => TypeScriptExactJson.HasExact(type, context.DocumentContext, [])))
            throw new InvalidOperationException($"SignalR hub '{hub.Name}' uses unquoted exact JSON numbers. Declare these values as strings for the JavaScript client.");

        var dependencies = new IrTypeDependencyGraphBuilder();
        var imports = types.SelectMany(dependencies.ExtractDependenciesFromType)
            .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal)
            .Select(name => BuildModelImport(context, hub, name)).ToArray();
        var typeBuilder = new TypeScriptAstBuilder(context.DocumentContext, naming, context.PluginOptions as TypeScriptGenerationOptions);
        var methods = new ObjectLiteralExpressionNode(
            hub.Methods.Select(method => BuildMethod(typeBuilder, method)).ToArray(), preferMultilineFormat: true);
        var events = new ObjectLiteralExpressionNode(
            hub.Events.Select(notification => BuildEvent(typeBuilder, notification)).ToArray(), preferMultilineFormat: true);
        var client = new ObjectLiteralExpressionNode(
            [new(new("methods"), methods), new(new("events"), events)], preferMultilineFormat: true);
        var connectionMethods = new UnionTypeNode([MethodLiteral("invoke"), MethodLiteral("on"), MethodLiteral("off")]);
        var connectionType = new GenericTypeNode(new("Pick"),
            [new ImportTypeNode("@microsoft/signalr", new("HubConnection")), connectionMethods]);
        var factory = new FunctionDeclarationNode(new("create" + hub.Name + "SignalRClient"),
            parameters: [new(new("connection"), connectionType)], body: new BlockNode([new ReturnStatementNode(client)]),
            documentation: new CommentNode("Wraps an existing connection with the hub's typed methods and subscriptions.", CommentKind.JSDoc),
            isExported: true);
        var path = new VariableDeclarationNode(new(naming.ToCamelCase(hub.Name) + "HubPath"),
            initializer: Literal(hub.Path), documentation: new CommentNode("Path declared by the owner for this hub.", CommentKind.JSDoc),
            isExported: true);

        return new SourceFileNode(imports: imports, declarations: [path, factory],
            fileDocumentation: new CommentNode("Generated by ValIO."));
    }

    /// <summary>Locates a type declaration relative to the generated SignalR module.</summary>
    /// <param name="context">The profile that determines the filenames.</param>
    /// <param name="hub">The hub that refers to the type.</param>
    /// <param name="name">The final symbol name, including configured affixes.</param>
    /// <returns>A type-only import for the referenced model or enum.</returns>
    /// <exception cref="InvalidOperationException">The type reference has no declaration in the document.</exception>
    private ImportNode BuildModelImport(GenerationContext context, IrSignalRHub hub, string name)
    {
        var originalName = context.DocumentContext.ModelsByName.TryGetValue(name, out var model) ? model.OriginalName :
            context.DocumentContext.EnumsByName.TryGetValue(name, out var enumType) ? enumType.OriginalName :
            throw new InvalidOperationException($"SignalR hub '{hub.Name}' references unknown schema '{name}'.");
        var path = (context.Configuration.FileOrganization.ModelsPath ?? "models").Replace('\\', '/');
        var fileName = naming.ToCamelCase(originalName);
        var module = context.Configuration.FileOrganization.SeparateModels
            ? $"{path}/{fileName}/{fileName}" : $"{path}/{fileName}";
        var relative = Path.GetRelativePath("signalr", module).Replace('\\', '/');
        var import = relative.StartsWith(".", StringComparison.Ordinal) ? relative : "./" + relative;
        return new ImportNode([new(name)], import, isTypeOnly: true);
    }

    /// <summary>Creates a callable property that invokes a server method with positional arguments.</summary>
    /// <param name="types">The profile-specific mapper of IR types.</param>
    /// <param name="method">The incoming method contract.</param>
    /// <returns>The method property and its typed arrow function.</returns>
    private static PropertyAssignmentNode BuildMethod(TypeScriptAstBuilder types, IrSignalRCall method)
    {
        var parameters = Parameters(types, method);
        var arguments = parameters.Select(parameter => new IdentifierExpressionNode(parameter.Name));
        var result = method.Result is null ? new SimpleTypeNode(new("void")) : types.BuildType(method.Result);
        var invoke = new CallExpressionNode(ConnectionMember("invoke"),
            [Literal(method.Name), .. arguments], genericTypeArgument: result);

        return new PropertyAssignmentNode(new(method.Name), new ArrowFunctionExpressionNode(parameters, invoke));
    }

    /// <summary>Creates a property that binds the given handler and returns its individual unsubscribe function.</summary>
    /// <param name="types">The profile-specific mapper of IR types.</param>
    /// <param name="notification">The outgoing event contract.</param>
    /// <returns>The subscription property and its typed arrow function.</returns>
    private static PropertyAssignmentNode BuildEvent(TypeScriptAstBuilder types, IrSignalRCall notification)
    {
        var handlerType = new FunctionTypeNode(Parameters(types, notification), new SimpleTypeNode(new("void")));
        var handler = new IdentifierExpressionNode(new IdentifierNode("handler"));
        var on = new CallExpressionNode(ConnectionMember("on"), [Literal(notification.Name), handler]);
        var off = new CallExpressionNode(ConnectionMember("off"), [Literal(notification.Name), handler]);
        var unsubscribe = new ArrowFunctionExpressionNode([], off);
        var body = new BlockNode([new ExpressionStatementNode(on), new ReturnStatementNode(unsubscribe)]);
        return new PropertyAssignmentNode(new(notification.Name),
            new ArrowFunctionExpressionNode([new(new("handler"), handlerType)], body));
    }

    /// <summary>Builds stable local arguments from the ordered wire signature.</summary>
    /// <param name="types">The profile-specific mapper of IR types.</param>
    /// <param name="call">The contract that declares the arguments.</param>
    /// <returns>The typed parameter declarations.</returns>
    private static ParameterDeclarationNode[] Parameters(TypeScriptAstBuilder types, IrSignalRCall call) =>
        call.Parameters.Select(parameter => new ParameterDeclarationNode(new("_" + parameter.Name),
            types.BuildType(parameter.Type))).ToArray();

    /// <summary>Selects an operation of the configured connection.</summary>
    /// <param name="method">The runtime method name.</param>
    /// <returns>The selected member expression.</returns>
    private static MemberAccessExpressionNode ConnectionMember(string method) =>
        new(new IdentifierExpressionNode(new IdentifierNode("connection")), new(method));

    /// <summary>Creates the literal type used to select a connection operation.</summary>
    /// <param name="name">The name of an operation on the official runtime connection.</param>
    /// <returns>The corresponding string literal type.</returns>
    private static TypeNode MethodLiteral(string name) => new SimpleTypeNode(new("string"), literalValue: name);

    /// <summary>Records a wire name or route for the TypeScript printer to escape.</summary>
    /// <param name="value">The raw text.</param>
    /// <returns>The literal expression.</returns>
    private static LiteralExpressionNode Literal(string value) => new(value, LiteralKind.String);
}
