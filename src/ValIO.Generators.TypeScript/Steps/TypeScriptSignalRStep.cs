using System.Text;
using System.Text.Json;
using ValIO.Core.Interfaces;
using ValIO.Core.IR;
using ValIO.Core.IR.Builders;
using ValIO.Core.IR.Types;
using ValIO.Core.Plugins;
using ValIO.Generators.TypeScript.Ast.Builders;
using ValIO.Generators.TypeScript.Ast.Renderers;
using ValIO.Generators.TypeScript.Options;

namespace ValIO.Generators.TypeScript.Steps;

/// <summary>Emits typed invocations and subscriptions over an existing JavaScript SignalR connection.</summary>
/// <param name="naming">The converter used to locate generated model modules.</param>
/// <param name="nodeRenderers">The node renderers registered for this language pipeline.</param>
internal sealed class TypeScriptSignalRStep(INamingConverter naming, IEnumerable<ITypeScriptNodeRenderer> nodeRenderers)
    : ICodeGenerationStep
{
    /// <summary>Renders hub signature types with the same rules as TypeScript model files.</summary>
    private readonly TypeScriptAstRenderer _renderer = new(nodeRenderers);

    /// <inheritdoc />
    public string Name => "typescript-signalr";

    /// <inheritdoc />
    public int Order => 65;

    /// <inheritdoc />
    public bool ShouldExecute(GenerationContext context) =>
        context.Configuration.GenerateClients && context.IrDocument.SignalRHubs.Count > 0;

    /// <inheritdoc />
    public Task ExecuteAsync(GenerationContext context, CancellationToken ct = default)
    {
        var builder = new TypeScriptAstBuilder(context.DocumentContext, naming, context.PluginOptions as TypeScriptGenerationOptions);
        foreach (var hub in context.IrDocument.SignalRHubs)
        {
            ct.ThrowIfCancellationRequested();
            var fileName = naming.ToCamelCase(hub.Name) + "SignalR";
            var content = RenderHub(context, builder, hub);
            context.GeneratedFiles.Add(new GeneratedFile($"signalr/{fileName}.ts", content));
        }

        return Task.CompletedTask;
    }

    /// <summary>Renders one client module and the imports used by its method and event signatures.</summary>
    /// <param name="context">The current request with generated model and enum file conventions.</param>
    /// <param name="builder">The TypeScript builder for this request.</param>
    /// <param name="hub">The source hub contract.</param>
    /// <returns>A TypeScript module exposing the path and the typed client factory.</returns>
    private string RenderHub(GenerationContext context, TypeScriptAstBuilder builder, IrSignalRHub hub)
    {
        var text = new StringBuilder().AppendLine("// Generated by ValIO.").AppendLine();
        var models = context.DocumentContext.ModelsByName;
        var enums = context.DocumentContext.EnumsByName;
        var path = (context.Configuration.FileOrganization.ModelsPath ?? "models").Replace('\\', '/');
        var dependencies = new IrTypeDependencyGraphBuilder();
        var signatureTypes = hub.Methods.Concat(hub.Events).SelectMany(call =>
            call.Result is null ? call.Parameters.Select(parameter => parameter.Type) :
                call.Parameters.Select(parameter => parameter.Type).Append(call.Result));
        var types = signatureTypes.ToArray();
        if (types.Any(type => TypeScriptExactJson.HasExact(type, context.DocumentContext, [])))
            throw new InvalidOperationException($"SignalR hub '{hub.Name}' uses unquoted exact JSON numbers. Declare these values as strings for the JavaScript client.");

        var referencedTypes = types.SelectMany(dependencies.ExtractDependenciesFromType)
            .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal);

        foreach (var name in referencedTypes)
        {
            var originalName = models.TryGetValue(name, out var model) ? model.OriginalName :
                enums.TryGetValue(name, out var enumType) ? enumType.OriginalName :
                throw new InvalidOperationException($"SignalR hub '{hub.Name}' references unknown schema '{name}'.");
            var fileName = naming.ToCamelCase(originalName);
            var module = context.Configuration.FileOrganization.SeparateModels
                ? $"{path}/{fileName}/{fileName}" : $"{path}/{fileName}";
            var relative = Path.GetRelativePath("signalr", module).Replace('\\', '/');
            var import = relative.StartsWith(".", StringComparison.Ordinal) ? relative : "./" + relative;
            text.AppendLine($"import type {{ {name} }} from {JsonSerializer.Serialize(import)};");
        }

        text.AppendLine();
        text.AppendLine("/** Path declared by the owner for this hub. */");
        text.AppendLine($"export const {naming.ToCamelCase(hub.Name)}HubPath = {JsonSerializer.Serialize(hub.Path)};");
        text.AppendLine();
        text.AppendLine("/** Wraps an existing connection with the hub's typed methods and subscriptions. */");
        text.AppendLine($"export function create{hub.Name}SignalRClient(connection: Pick<import(\"@microsoft/signalr\").HubConnection, \"invoke\" | \"on\" | \"off\">) {{");
        text.AppendLine("  return {");
        text.AppendLine("    methods: {");
        foreach (var method in hub.Methods)
        {
            var parameters = Parameters(builder, method);
            var arguments = string.Concat(method.Parameters.Select(parameter => ", _" + parameter.Name));
            var result = method.Result is null ? "void" : RenderType(builder, method.Result);
            text.AppendLine($"      {method.Name}({parameters}) {{");
            text.AppendLine($"        return connection.invoke<{result}>(\"{method.Name}\"{arguments});");
            text.AppendLine("      },");
        }

        text.AppendLine("    },");
        text.AppendLine("    events: {");
        foreach (var notification in hub.Events)
        {
            var parameters = Parameters(builder, notification);
            text.AppendLine($"      {notification.Name}(handler: ({parameters}) => void) {{");
            text.AppendLine($"        connection.on(\"{notification.Name}\", handler);");
            text.AppendLine($"        return () => connection.off(\"{notification.Name}\", handler);");
            text.AppendLine("      },");
        }
        return text.AppendLine("    },").AppendLine("  };").AppendLine("}").ToString();
    }

    /// <summary>Renders the ordered TypeScript argument list.</summary>
    /// <param name="builder">The builder applying the configured type mapping.</param>
    /// <param name="call">The hub method or event.</param>
    /// <returns>The positional argument declarations.</returns>
    private string Parameters(TypeScriptAstBuilder builder, IrSignalRCall call) =>
        string.Join(", ", call.Parameters.Select(parameter => $"_{parameter.Name}: {RenderType(builder, parameter.Type)}"));

    /// <summary>Renders one wire type using the existing TypeScript model conventions.</summary>
    /// <param name="builder">The configured model builder.</param>
    /// <param name="type">The normalized wire type.</param>
    /// <returns>The generated type expression.</returns>
    private string RenderType(TypeScriptAstBuilder builder, IrType type) => builder.BuildType(type).Accept(_renderer);
}
